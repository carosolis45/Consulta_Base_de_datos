SELECT 
    ROUND(SUM(A.HONORARIO)) AS HONORARIO,
    P.ID_PROFESIONAL,
    P.NUMRUN_PROF,
    P.SUELDO
FROM PROFESIONAL P
INNER JOIN ASESORIA A ON P.ID_PROFESIONAL = A.ID_PROFESIONAL
WHERE EXTRACT(YEAR FROM A.FIN_ASESORIA) = EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -12))
  AND EXTRACT(MONTH FROM A.FIN_ASESORIA) = 3
GROUP BY P.ID_PROFESIONAL, P.NUMRUN_PROF, P.SUELDO
ORDER BY P.ID_PROFESIONAL ASC;

--actualizacion

UPDATE PROFESIONAL 
SET SUELDO = CASE 
    WHEN (SELECT ROUND(SUM(A.HONORARIO)) 
          FROM ASESORIA A 
          WHERE A.ID_PROFESIONAL = PROFESIONAL.ID_PROFESIONAL
          AND EXTRACT(YEAR FROM A.FIN_ASESORIA) = EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -12))
          AND EXTRACT(MONTH FROM A.FIN_ASESORIA) = 3) < 1000000 
    THEN ROUND(SUELDO * 1.10)  -- 10% de incremento
    
    WHEN (SELECT ROUND(SUM(A.HONORARIO)) 
          FROM ASESORIA A 
          WHERE A.ID_PROFESIONAL = PROFESIONAL.ID_PROFESIONAL
          AND EXTRACT(YEAR FROM A.FIN_ASESORIA) = EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -12))
          AND EXTRACT(MONTH FROM A.FIN_ASESORIA) = 3) >= 1000000 
    THEN ROUND(SUELDO * 1.15)  -- 15% de incremento
    
    ELSE SUELDO  -- Mantiene sueldo si no cumple condiciones
END
WHERE ID_PROFESIONAL IN (
    SELECT DISTINCT P.ID_PROFESIONAL
    FROM PROFESIONAL P
    INNER JOIN ASESORIA A ON P.ID_PROFESIONAL = A.ID_PROFESIONAL
    WHERE EXTRACT(YEAR FROM A.FIN_ASESORIA) = EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -12))
      AND EXTRACT(MONTH FROM A.FIN_ASESORIA) = 3
);

