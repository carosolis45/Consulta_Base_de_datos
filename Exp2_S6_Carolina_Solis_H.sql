CREATE TABLE REPORTE_MES (
    id_profesional NUMBER(10),
    nombre_completo VARCHAR2(60),
    nombre_profesion VARCHAR2(25),
    nombre_comuna VARCHAR2(20),
    nro_asesorias NUMBER(3),
    monto_total_honorarios NUMBER(10),
    promedio_honorarios NUMBER(10),
    honorario_minimo NUMBER(10),
    honorario_maximo NUMBER(10)
);

INSERT INTO REPORTE_MES (
    id_profesional,
    nombre_completo,
    nombre_profesion,
    nombre_comuna,
    nro_asesorias,
    monto_total_honorarios,
    promedio_honorarios,
    honorario_minimo,
    honorario_maximo
)
SELECT 
    P.ID_PROFESIONAL,
    UPPER(SUBSTR(P.APPATERNO, 1, 1)) || LOWER(SUBSTR(P.APPATERNO, 2)) || ' ' ||
    UPPER(SUBSTR(P.APMATERNO, 1, 1)) || LOWER(SUBSTR(P.APMATERNO, 2)) || ' ' ||
    UPPER(SUBSTR(P.NOMBRE, 1, 1)) || LOWER(SUBSTR(P.NOMBRE, 2)) AS nombre_completo,
    NVL(PR.NOMBRE_PROFESION, 'SIN PROFESION') AS nombre_profesion,
    NVL(C.NOM_COMUNA, 'SIN COMUNA') AS nombre_comuna,
    COUNT(A.ID_PROFESIONAL) AS nro_asesorias,
    ROUND(NVL(SUM(A.HONORARIO), 0)) AS monto_total_honorarios,
    ROUND(NVL(AVG(A.HONORARIO), 0)) AS promedio_honorarios,
    ROUND(NVL(MIN(A.HONORARIO), 0)) AS honorario_minimo,
    ROUND(NVL(MAX(A.HONORARIO), 0)) AS honorario_maximo
FROM PROFESIONAL P
INNER JOIN ASESORIA A ON P.ID_PROFESIONAL = A.ID_PROFESIONAL
INNER JOIN PROFESION PR ON P.COD_PROFESION = PR.COD_PROFESION
INNER JOIN COMUNA C ON P.COD_COMUNA = C.COD_COMUNA
WHERE EXTRACT(YEAR FROM A.FIN_ASESORIA) = EXTRACT(YEAR FROM ADD_MONTHS(SYSDATE, -12))
  AND EXTRACT(MONTH FROM A.FIN_ASESORIA) = 4
GROUP BY 
    P.ID_PROFESIONAL,
    P.APPATERNO,
    P.APMATERNO,
    P.NOMBRE,
    PR.NOMBRE_PROFESION,
    C.NOM_COMUNA
ORDER BY P.ID_PROFESIONAL ASC;

SELECT * FROM REPORTE_MES ORDER BY id_profesional ASC;



