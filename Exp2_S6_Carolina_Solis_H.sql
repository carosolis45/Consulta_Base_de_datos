SELECT 
    ID_PROFESIONAL AS "Id Profesional",
    NOMBRE_COMPLETO AS "Nombre Completo",
    CANTIDAD_BANCA AS "N° Asesorías Banca",
    MONTO_BANCA AS "Monto Total Banca",
    CANTIDAD_RETAIL AS "N° Asesorías Retail", 
    MONTO_RETAIL AS "Monto Total Retail",
    (CANTIDAD_BANCA + CANTIDAD_RETAIL) AS "Total Asesorías",
    (MONTO_BANCA + MONTO_RETAIL) AS "Total Honorarios"
FROM (
    SELECT 
        P.ID_PROFESIONAL,
        INITCAP(P.APPATERNO || ' ' || P.APMATERNO || ' ' || P.NOMBRE) AS NOMBRE_COMPLETO,
        NVL((SELECT COUNT(*) 
             FROM ASESORIA A 
             INNER JOIN EMPRESA E ON A.COD_EMPRESA = E.COD_EMPRESA
             WHERE A.ID_PROFESIONAL = P.ID_PROFESIONAL 
             AND E.COD_SECTOR = 3
        ), 0) AS CANTIDAD_BANCA,
        
        NVL((SELECT SUM(A.HONORARIO)
             FROM ASESORIA A 
             INNER JOIN EMPRESA E ON A.COD_EMPRESA = E.COD_EMPRESA
             WHERE A.ID_PROFESIONAL = P.ID_PROFESIONAL 
             AND E.COD_SECTOR = 3
        ), 0) AS MONTO_BANCA,
        
        NVL((SELECT COUNT(*) 
             FROM ASESORIA A 
             INNER JOIN EMPRESA E ON A.COD_EMPRESA = E.COD_EMPRESA
             WHERE A.ID_PROFESIONAL = P.ID_PROFESIONAL 
             AND E.COD_SECTOR = 4
        ), 0) AS CANTIDAD_RETAIL,
        
        NVL((SELECT SUM(A.HONORARIO)
             FROM ASESORIA A 
             INNER JOIN EMPRESA E ON A.COD_EMPRESA = E.COD_EMPRESA
             WHERE A.ID_PROFESIONAL = P.ID_PROFESIONAL 
             AND E.COD_SECTOR = 4
        ), 0) AS MONTO_RETAIL
        
    FROM PROFESIONAL P
    WHERE P.ID_PROFESIONAL IN (
        SELECT A1.ID_PROFESIONAL
        FROM ASESORIA A1
        INNER JOIN EMPRESA E1 ON A1.COD_EMPRESA = E1.COD_EMPRESA
        WHERE E1.COD_SECTOR = 3
        
        INTERSECT
        
        SELECT A2.ID_PROFESIONAL
        FROM ASESORIA A2
        INNER JOIN EMPRESA E2 ON A2.COD_EMPRESA = E2.COD_EMPRESA
        WHERE E2.COD_SECTOR = 4
    )
)
WHERE CANTIDAD_BANCA > 0 AND CANTIDAD_RETAIL > 0
ORDER BY "Id Profesional" ASC



